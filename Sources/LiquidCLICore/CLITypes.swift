import Foundation
import ArgumentParser

/// Errors specific to CLI operations.
enum CLIError: Error, CustomStringConvertible {
    case fileNotFound(String)
    case invalidFormat(String)
    case renderFailed(String)
    case directoryCreationFailed(String)

    var description: String {
        switch self {
        case .fileNotFound(let path): return "File not found: \(path)"
        case .invalidFormat(let msg): return "Invalid format: \(msg)"
        case .renderFailed(let msg): return "Render failed: \(msg)"
        case .directoryCreationFailed(let path): return "Could not create directory: \(path)"
        }
    }
}

